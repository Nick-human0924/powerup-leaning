// Inspect an exported archive only in a disposable browser context.
import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
const archive=process.argv[2];
if(!archive)throw new Error('Provide a local JSON export path.');
const source=JSON.parse(fs.readFileSync(archive,'utf8'));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const context=await browser.newContext({viewport:{width:375,height:812},reducedMotion:'reduce'});
const page=await context.newPage();
await page.goto('http://127.0.0.1:3001');
await page.getByRole('button',{name:/我带安哲练/}).waitFor();
await page.getByRole('navigation',{name:'主要页面'}).getByRole('button',{name:'记录',exact:true}).click();
await page.locator('.backup-card input[type=file]').setInputFiles(archive);
await expect(page.getByText('备份已合并')).toBeVisible();
await expect(page.locator('.record-list article')).toHaveCount(source.observations.length);
await expect(page.locator('.record-list .status-pill').filter({hasText:'提示后说出'})).toHaveCount(source.observations.filter(x=>x.outcome==='prompted').length);
fs.mkdirSync('docs/pm-review/rendered-v2',{recursive:true});
await page.screenshot({path:'docs/pm-review/rendered-v2/records-preserved-375.png',fullPage:true});
const lastControl=page.getByRole('button',{name:'清除本机数据',exact:true});
await lastControl.scrollIntoViewIfNeeded();
const bounds=await lastControl.boundingBox();
const navBounds=await page.locator('.bottom-nav').boundingBox();
expect(bounds.y+bounds.height).toBeLessThanOrEqual(navBounds.y);
await lastControl.click();
await expect(page.getByRole('button',{name:'取消',exact:true})).toBeVisible();
await page.getByRole('button',{name:'取消',exact:true}).click();
await expect(page.locator('.record-list article')).toHaveCount(source.observations.length);
console.log(JSON.stringify({preservedObservations:source.observations.length,prompted:source.observations.filter(x=>x.outcome==='prompted').length,lastControlAboveNavigation:true,isolatedContext:true}));
await browser.close();
